#!/bin/sh
# Collect the phase 2 modules the first Android ramdisk has to load.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
MODSRC=${1:-${MODSRC:-}}
if [ -z "$MODSRC" ] || [ ! -f "$MODSRC/modules.dep" ]; then
    echo "Usage: $0 /path/to/lib/modules/6.6.34-phase2" >&2
    exit 1
fi
DEST=$ROOT/prebuilt/6.6.34-phase2
python3 - "$MODSRC" "$DEST" "$ROOT/modules.mk" << 'PY'
import os, pathlib, subprocess, sys
src, dest, mk_path = sys.argv[1:]
dep = {}
for line in open(os.path.join(src, "modules.dep")):
    line = line.strip()
    if not line:
        continue
    left, _, right = line.partition(":")
    dep[left] = right.split()
seeds = []
for path in dep:
    base = os.path.basename(path)
    if base.startswith("nft_") or base.startswith("nf_tables") or base.startswith("xt_"):
        seeds.append(path)
for extra in (
    "kernel/drivers/gpu/drm/panel/panel-kingdisplay-kd097d04.ko.xz",
    "kernel/drivers/usb/gadget/function/usb_f_fs.ko.xz",
    "kernel/drivers/input/touchscreen/elants_i2c.ko.xz",
    "kernel/drivers/input/keyboard/cros_ec_keyb.ko.xz",
    "kernel/drivers/power/supply/sbs-battery.ko.xz",
    "kernel/drivers/phy/rockchip/phy-rockchip-inno-dsidphy.ko.xz",
    "kernel/drivers/block/loop.ko.xz",
    "kernel/net/xfrm/xfrm_user.ko.xz",
    "kernel/drivers/input/misc/uinput.ko.xz",
):
    if extra not in dep:
        raise SystemExit("missing " + extra)
    seeds.append(extra)
seen = set()
order = []
def visit(path):
    if path in seen:
        return
    seen.add(path)
    if path not in dep:
        raise SystemExit("missing dep " + path)
    for item in dep[path]:
        visit(item)
    order.append(path)
for path in seeds:
    visit(path)
pathlib.Path(dest).mkdir(parents=True, exist_ok=True)
for old in pathlib.Path(dest).glob("*.ko"):
    old.unlink()
names = []
dep_lines = []
for path in order:
    name = os.path.basename(path).removesuffix(".xz")
    target = os.path.join(dest, name)
    data = subprocess.check_output(["xz", "-dc", os.path.join(src, path)])
    with open(target, "wb") as out:
        out.write(data)
    names.append(name)
    deps = [os.path.basename(item).removesuffix(".xz") for item in dep[path]]
    # No trailing space. Android splits on spaces, and an empty field becomes
    # the module directory itself, which first-stage init then refuses to load.
    dep_lines.append(name + (": " + " ".join(deps) if deps else ":"))
with open(os.path.join(dest, "modules.dep"), "w") as out:
    out.write("\n".join(dep_lines) + "\n")
with open(os.path.join(dest, "modules.load"), "w") as out:
    out.write("\n".join(names) + "\n")
copies = []
for name in names + ["modules.dep", "modules.load"]:
    copies.append(
        "    $(LOCAL_PATH)/prebuilt/6.6.34-phase2/%s:$(TARGET_COPY_OUT_RAMDISK)/lib/modules/6.6.34-phase2/%s"
        % (name, name)
    )
with open(mk_path, "w") as out:
    out.write("# Generated by prepare-ramdisk-modules.sh. Do not edit.\n")
    out.write("PRODUCT_COPY_FILES += \\\n")
    out.write(" \\\n".join(copies) + "\n")
print("modules", len(names))
PY
